export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('ahk_factory_lang') || 'ru';
  });

  const changeLanguage = (newLang) => {
    if (translations[newLang]) {
      setLang(newLang);
      localStorage.setItem('ahk_factory_lang', newLang);
    }
  };

  const t = (key) => {
    const val = translations[lang]?.[key];
    if (typeof val === 'string' && val.trim().length > 0) return val;
    const ruVal = translations['ru']?.[key];
    if (typeof ruVal === 'string' && ruVal.trim().length > 0) return ruVal;
    return key;
  };

  const tCategory = (cat) => {
    if (!cat) return '';
    const key = String(cat).toLowerCase().trim();
    const val = categoryTranslations[lang]?.[key];
    if (typeof val === 'string' && val.trim().length > 0) return val;
    const ruVal = categoryTranslations['ru']?.[key];
    if (typeof ruVal === 'string' && ruVal.trim().length > 0) return ruVal;
    return cat;
  };

  const tProduct = (product) => {
    if (!product) return product;

    // Считываем перевод на текущем языке (например, 'tr') и русский fallback ('ru')
    const currentTrans = productTranslations[lang]?.[product.id] || {};
    const ruTrans = productTranslations['ru']?.[product.id] || {};

    // Гарантированное получение поля: если на текущем языке нет перевода или пустая строка,
    // автоматически откатываемся на русский перевод, затем на исходное свойство товара
    const getField = (field) => {
      const currentVal = currentTrans[field];
      if (typeof currentVal === 'string' && currentVal.trim().length > 0) {
        return currentVal;
      }
      const ruVal = ruTrans[field];
      if (typeof ruVal === 'string' && ruVal.trim().length > 0) {
        return ruVal;
      }
      return product[field] || '';
    };

    const cat = tCategory(product.category) || product.category;

    let badge = currentTrans.badge;
    if (!badge || (typeof badge === 'string' && badge.trim().length === 0)) {
      badge = ruTrans.badge !== undefined && ruTrans.badge !== '' ? ruTrans.badge : product.badge;
    }

    return {
      ...product,
      title: getField('title'),
      description: getField('description'),
      material: getField('material'),
      dimensions: getField('dimensions'),
      badge,
      wood_type: getField('wood_type'),
      category: cat
    };
  };

  return (
    <LanguageContext.Provider value={{ lang, changeLanguage, t, tCategory, tProduct }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
};
